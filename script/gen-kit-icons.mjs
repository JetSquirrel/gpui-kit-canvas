/**
 * Generates lib/kit-icons.gen.ts from a gpui-kit checkout.
 *
 * The canvas offers exactly the icons gpui-kit ships, so a sketch can never
 * name an icon the generated app cannot draw. `IconName` is derived from the
 * file names by the icon_named! macro in crates/component/src/icon.rs, so the
 * PascalCase spelling here is the one the prompt quotes.
 *
 *   node script/gen-kit-icons.mjs [path-to-gpui-kit]
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const KIT = resolve(process.argv[2] ?? process.env.GPUI_KIT ?? join(here, "..", "..", "gpui-kit"));
const DIR = join(KIT, "crates", "assets", "assets", "icons");

const pascal = (name) =>
  name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const attr = (tag, name) => tag.match(new RegExp(`${name}="([^"]*)"`))?.[1];

const icons = readdirSync(DIR)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((file) => {
    const name = file.replace(/\.svg$/, "");
    const svg = readFileSync(join(DIR, file), "utf8");
    const open = svg.match(/<svg\b[^>]*>/)?.[0] ?? "";
    const body = svg
      .replace(/<\?xml[\s\S]*?\?>/g, "")
      .replace(/<svg\b[^>]*>/, "")
      .replace(/<\/svg>/, "")
      .replace(/<!--[\s\S]*?-->/g, "")
      // A few of the window-control glyphs are drawn as filled paths with a
      // literal black fill. The canvas colours icons through `currentColor`,
      // so a literal colour would ignore the theme.
      .replace(/(fill|stroke)="#[0-9a-fA-F]{3,8}"/g, '$1="currentColor"')
      // Collapse whitespace to single spaces: a newline can sit between two
      // attributes, so dropping it outright would glue them together.
      .replace(/\s+/g, " ")
      .replace(/>\s+</g, "><")
      .trim();
    /* A Lucide icon strokes `currentColor`; the window-control glyphs fill it.
     * Read which one the file means so the canvas paints it the same way. */
    const strokes = attr(open, "stroke") === "currentColor" || /stroke="currentColor"/.test(body);
    return {
      name,
      pascal: pascal(name),
      view: attr(open, "viewBox") ?? "0 0 24 24",
      fill: strokes ? (attr(open, "fill") ?? "none") : "currentColor",
      stroke: strokes ? "currentColor" : "none",
      width: attr(open, "stroke-width") ?? "2",
      body,
    };
  });

const ts = `// Generated by script/gen-kit-icons.mjs from a gpui-kit checkout. Do not edit.
// Regenerate with: node script/gen-kit-icons.mjs [path-to-gpui-kit]

export type KitIcon = {
  /** the file name gpui-kit ships, and the name the canvas stores */
  name: string;
  /** the \`IconName\` variant the prompt quotes */
  pascal: string;
  view: string;
  fill: string;
  stroke: string;
  width: string;
  /** the svg's inner markup */
  body: string;
};

export const KIT_ICONS: KitIcon[] = [
${icons
  .map(
    (i) =>
      `  { name: ${JSON.stringify(i.name)}, pascal: ${JSON.stringify(i.pascal)}, view: ${JSON.stringify(
        i.view
      )}, fill: ${JSON.stringify(i.fill)}, stroke: ${JSON.stringify(i.stroke)}, width: ${JSON.stringify(
        i.width
      )}, body: ${JSON.stringify(i.body)} }`
  )
  .join(",\n")},
];

export const KIT_ICON_BY_NAME: Record<string, KitIcon> = Object.fromEntries(
  KIT_ICONS.map((i) => [i.name, i])
);

/** the \`IconName\` variant for a stored icon name, e.g. "chevron-down" -> "ChevronDown" */
export const iconVariant = (name: string) => KIT_ICON_BY_NAME[name]?.pascal ?? pascalOf(name);

const pascalOf = (name: string) =>
  name
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
`;

writeFileSync(join(here, "..", "lib", "kit-icons.gen.ts"), ts);
console.log(`wrote lib/kit-icons.gen.ts — ${icons.length} icons`);
